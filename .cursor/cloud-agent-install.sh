#!/usr/bin/env bash
# Idempotent update command for Cursor Cloud Agents (Excalibur BLOG).
set -euo pipefail

echo "[excalibur-cloud] install start"
python3 --version
git --version

python3 -m pip install --break-system-packages --quiet \
  requests pillow python-dotenv paramiko 2>/dev/null \
  || python3 -m pip install --quiet requests pillow python-dotenv paramiko

mkdir -p .cursor/excalibur-blog-fragments
touch .cursor/excalibur-blog-handoff.md

# Publish transport reads memory/site.env.local (gitignored). Bootstrap from
# Cloud Secrets / process env when the file is missing so SSH publish can start.
if [ ! -f memory/site.env.local ] && [ -f memory/site.env.local.example ]; then
  mkdir -p memory
  # Prefer process env over example placeholders; never print secret values.
  {
    echo "# Auto-generated by cloud-agent-install.sh — do not commit"
    for key in \
      PUBLIC_SITE_URL WP_SITE_URL WP_HOME \
      SSH_HOST SSH_USER SSH_PASS SSH_PASSWORD SSH_PORT SSH_ROOT \
      EXCALIBUR_BLOG_ALLOW_PUBLISH CATALOG_URL TELEGRAM_URL
    do
      # bash nameref-safe read under set -u
      if [ -n "${!key+x}" ]; then
        val="${!key}"
        if [ -n "${val}" ]; then
          printf '%s=%s\n' "$key" "$val"
        fi
      fi
    done
    # This SSH account expects login cwd when panel root is absent.
    if [ -z "${SSH_ROOT-}" ]; then
      echo "SSH_ROOT=."
    fi
  } > memory/site.env.local
  echo "[excalibur-cloud] bootstrapped memory/site.env.local from env (gitignored)"
fi

echo "[excalibur-cloud] install ok"
