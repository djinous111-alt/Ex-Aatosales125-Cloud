#!/usr/bin/env bash
# Idempotent update command for Cursor Cloud Agents (Excalibur BLOG).
set -euo pipefail

echo "[excalibur-cloud] install start"
python3 --version
git --version

# Keep in sync with requirements.txt + Dockerfile (paramiko required for SSH publish).
python3 -m pip install --break-system-packages --quiet \
  requests pillow python-dotenv numpy paramiko 2>/dev/null \
  || python3 -m pip install --quiet requests pillow python-dotenv numpy paramiko

# Filter CLOUD_AGENT_INJECTED_SECRET_NAMES to bash-safe identifiers only.
# Non-identifiers break pre-commit.cursor `${!SECRET_NAME}` with "invalid variable name".
if [[ -n "${CLOUD_AGENT_INJECTED_SECRET_NAMES:-}" ]]; then
  _filtered=""
  IFS=',' read -r -a _secret_names <<< "${CLOUD_AGENT_INJECTED_SECRET_NAMES}"
  for _name in "${_secret_names[@]}"; do
    _name="$(echo "${_name}" | xargs)"
    if [[ "${_name}" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]]; then
      if [[ -z "${_filtered}" ]]; then
        _filtered="${_name}"
      else
        _filtered="${_filtered},${_name}"
      fi
    else
      echo "[excalibur-cloud] skip non-bash-safe secret name: ${_name}" >&2
    fi
  done
  export CLOUD_AGENT_INJECTED_SECRET_NAMES="${_filtered}"
fi

mkdir -p .cursor/excalibur-blog-fragments
touch .cursor/excalibur-blog-handoff.md

# Optional: materialize gitignored site.env.local from Cloud Secrets (no secret values printed).
if [[ ! -f memory/site.env.local ]] && [[ -n "${SSH_HOST:-}" || -n "${PUBLIC_SITE_URL:-}" ]]; then
  mkdir -p memory
  {
    echo "# generated by cloud-agent-install.sh — do not commit"
    [[ -n "${PUBLIC_SITE_URL:-}" ]] && echo "PUBLIC_SITE_URL=${PUBLIC_SITE_URL}"
    [[ -n "${WP_SITE_URL:-}" ]] && echo "WP_SITE_URL=${WP_SITE_URL}"
    [[ -n "${WP_HOME:-}" ]] && echo "WP_HOME=${WP_HOME}"
    [[ -n "${SSH_HOST:-}" ]] && echo "SSH_HOST=${SSH_HOST}"
    [[ -n "${SSH_PORT:-}" ]] && echo "SSH_PORT=${SSH_PORT}" || echo "SSH_PORT=22"
    [[ -n "${SSH_USER:-}" ]] && echo "SSH_USER=${SSH_USER}"
    [[ -n "${SSH_PASS:-}" ]] && echo "SSH_PASS=${SSH_PASS}"
    [[ -n "${SSH_PASSWORD:-}" ]] && echo "SSH_PASSWORD=${SSH_PASSWORD}"
    echo "SSH_ROOT=${SSH_ROOT:-.}"
    [[ -n "${EXCALIBUR_BLOG_ALLOW_PUBLISH:-}" ]] && echo "EXCALIBUR_BLOG_ALLOW_PUBLISH=${EXCALIBUR_BLOG_ALLOW_PUBLISH}"
    [[ -n "${CATALOG_URL:-}" ]] && echo "CATALOG_URL=${CATALOG_URL}"
    [[ -n "${TELEGRAM_URL:-}" ]] && echo "TELEGRAM_URL=${TELEGRAM_URL}"
    [[ -n "${MAX_URL:-}" ]] && echo "MAX_URL=${MAX_URL}"
  } > memory/site.env.local
  echo "[excalibur-cloud] wrote memory/site.env.local from Cloud Secrets (gitignored)"
fi

echo "[excalibur-cloud] install ok"
