#!/usr/bin/env python3
"""Bootstrap gitignored memory/site.env.local from Cloud Secrets / process env.

Does not print secret values. Safe to run from cloud-agent-install.sh.
Only writes when the file is missing (or --force). Never commits the file.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

KEYS = (
    "PUBLIC_SITE_URL",
    "WP_SITE_URL",
    "WP_HOME",
    "SSH_HOST",
    "SSH_PORT",
    "SSH_USER",
    "SSH_PASS",
    "SSH_PASSWORD",
    "SSH_ROOT",
    "SSH_PATH",
    "EXCALIBUR_BLOG_ALLOW_PUBLISH",
    "CATALOG_URL",
    "TELEGRAM_URL",
    "TELEGRAM_HANDLE",
    "MAX_URL",
)


def project_root() -> Path:
    env_root = os.environ.get("EXCALIBUR_PROJECT_ROOT", "").strip()
    if env_root:
        return Path(env_root)
    return Path(__file__).resolve().parents[1]


def main() -> int:
    ap = argparse.ArgumentParser(description="Bootstrap memory/site.env.local from env (no secret echo)")
    ap.add_argument("--force", action="store_true", help="Overwrite existing site.env.local")
    ap.add_argument("--dry-run", action="store_true", help="Report which keys would be written (names only)")
    args = ap.parse_args()

    root = project_root()
    target = root / "memory" / "site.env.local"
    example = root / "memory" / "site.env.local.example"

    present = [k for k in KEYS if os.environ.get(k)]
    if args.dry_run:
        print(
            f"would_write={not target.is_file() or args.force} "
            f"keys_present={len(present)} keys={','.join(present) or '(none)'}"
        )
        return 0

    if target.is_file() and not args.force:
        print(f"OK site.env.local exists ({target.relative_to(root)}); skip bootstrap")
        return 0

    if not present:
        print(
            "WARN no publish/CTA Cloud Secrets in process env; "
            f"copy {example.relative_to(root)} → memory/site.env.local manually",
            file=sys.stderr,
        )
        return 1

    lines: list[str] = [
        "# Auto-bootstrapped from Cloud Secrets / process env. DO NOT COMMIT.",
        "# Generated by scripts/excalibur_blog_site_env_bootstrap.py",
    ]
    # Prefer SSH_ROOT; map legacy SSH_PATH → SSH_ROOT when root unset.
    ssh_root = (os.environ.get("SSH_ROOT") or "").strip()
    ssh_path = (os.environ.get("SSH_PATH") or "").strip()
    for key in KEYS:
        if key in {"SSH_ROOT", "SSH_PATH", "SSH_PASS", "SSH_PASSWORD"}:
            continue
        value = (os.environ.get(key) or "").strip()
        if value:
            lines.append(f"{key}={value}")

    if ssh_root:
        lines.append(f"SSH_ROOT={ssh_root}")
    elif ssh_path:
        # Beget/login cwd often needs "."; keep path only if agent set SSH_PATH intentionally.
        lines.append(f"SSH_ROOT={ssh_path}")
        lines.append("# note: SSH_PATH mapped to SSH_ROOT for publish script")

    password = (os.environ.get("SSH_PASS") or os.environ.get("SSH_PASSWORD") or "").strip()
    if password:
        lines.append(f"SSH_PASSWORD={password}")

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    # Restrictive perms when possible (best-effort on shared FS).
    try:
        os.chmod(target, 0o600)
    except OSError:
        pass
    print(f"OK wrote memory/site.env.local keys={len(present)} (values not printed)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
